"""OpenAI-compatible chat client with free-tier-friendly retries.

Configured only by LLM_BASE_URL / LLM_MODEL / LLM_API_KEY, so Groq, Gemini's OpenAI
endpoint and Ollama are interchangeable through .env.
"""
from __future__ import annotations

import asyncio
import logging
import random
from dataclasses import dataclass, field
from typing import Any, Protocol

import openai

from beacon.config import Settings, get_settings

log = logging.getLogger("beacon.llm")


class LLMError(RuntimeError):
    pass


class ToolCallFormatError(LLMError):
    """The provider rejected a malformed tool call generated by the model (e.g. Groq tool_use_failed)."""


@dataclass
class ToolCall:
    id: str
    name: str
    arguments: str
    # Provider-specific fields that must be echoed back verbatim on the next turn
    # (e.g. Gemini 3's extra_content.google.thought_signature).
    extra: dict | None = None


@dataclass
class ChatResult:
    content: str | None
    tool_calls: list[ToolCall] = field(default_factory=list)
    finish_reason: str | None = None
    usage: dict | None = None
    raw: dict | None = None

    def assistant_message(self) -> dict:
        msg: dict[str, Any] = {"role": "assistant", "content": self.content or ""}
        if self.tool_calls:
            msg["tool_calls"] = [{"id": tc.id, "type": "function",
                                  "function": {"name": tc.name, "arguments": tc.arguments},
                                  **(tc.extra or {})}
                                 for tc in self.tool_calls]
        return msg


class ChatModel(Protocol):
    model: str
    provider: str

    async def chat(self, messages: list[dict], tools: list[dict] | None = None,
                   tool_choice: str | None = None, json_mode: bool = False) -> ChatResult: ...


def _retry_after_seconds(exc: openai.APIStatusError) -> float | None:
    headers = getattr(exc.response, "headers", None) or {}
    for key in ("retry-after", "x-ratelimit-reset-tokens", "x-ratelimit-reset-requests"):
        raw = headers.get(key)
        if not raw:
            continue
        try:
            return float(raw)
        except ValueError:
            # Groq style durations such as "7.66s" or "1m2.5s"
            total, num = 0.0, ""
            for ch in raw:
                if ch.isdigit() or ch == ".":
                    num += ch
                elif ch in "hms" and num:
                    total += float(num) * {"h": 3600, "m": 60, "s": 1}[ch]
                    num = ""
            if total:
                return total
    return None


class OpenAICompatibleLLM:
    def __init__(self, settings: Settings | None = None):
        s = settings or get_settings()
        if not s.llm_configured:
            raise LLMError("LLM is not configured: set LLM_BASE_URL, LLM_MODEL and LLM_API_KEY")
        self.settings = s
        self.model = s.llm_model
        self.provider = s.llm_base_url.split("//", 1)[-1].split("/", 1)[0]
        # Retries are handled here (honouring Retry-After), not inside the SDK.
        self.client = openai.AsyncOpenAI(base_url=s.llm_base_url, api_key=s.llm_api_key or "none",
                                         timeout=s.llm_timeout_seconds, max_retries=0)

    async def chat(self, messages: list[dict], tools: list[dict] | None = None,
                   tool_choice: str | None = None, json_mode: bool = False) -> ChatResult:
        kwargs: dict[str, Any] = {"model": self.model, "messages": messages,
                                  "temperature": self.settings.llm_temperature,
                                  "max_tokens": self.settings.llm_max_tokens}
        if self.settings.llm_reasoning_effort:
            kwargs["reasoning_effort"] = self.settings.llm_reasoning_effort
        if tools:
            kwargs["tools"] = tools
            kwargs["tool_choice"] = tool_choice or "auto"
        if json_mode:
            kwargs["response_format"] = {"type": "json_object"}

        attempt = 0
        while True:
            try:
                resp = await self.client.chat.completions.create(**kwargs)
                break
            except openai.RateLimitError as exc:
                attempt += 1
                if attempt > self.settings.llm_max_retries:
                    raise LLMError(f"rate limited after {attempt - 1} retries: {exc}") from exc
                wait = _retry_after_seconds(exc) or min(60.0, 2.0 ** attempt)
                wait = min(wait, 90.0) + random.uniform(0, 0.5)
                log.warning("LLM 429 (attempt %d), sleeping %.1fs", attempt, wait)
                await asyncio.sleep(wait)
            except openai.BadRequestError as exc:
                body = str(exc)
                if "tool_use_failed" in body or "Failed to call a function" in body:
                    raise ToolCallFormatError(body[:500]) from exc
                raise LLMError(f"bad request: {body[:500]}") from exc
            except (openai.APIConnectionError, openai.APITimeoutError, openai.InternalServerError) as exc:
                attempt += 1
                if attempt > self.settings.llm_max_retries:
                    raise LLMError(f"LLM unavailable: {exc}") from exc
                await asyncio.sleep(min(30.0, 2.0 ** attempt))
            except openai.APIStatusError as exc:
                raise LLMError(f"LLM error {exc.status_code}: {str(exc)[:300]}") from exc

        choice = resp.choices[0]
        msg = choice.message
        calls = []
        for tc in msg.tool_calls or []:
            extra = {k: v for k, v in tc.model_dump(exclude_none=True).items() if k not in ("id", "type", "function")}
            calls.append(ToolCall(tc.id, tc.function.name, tc.function.arguments or "{}", extra or None))
        usage = resp.usage.model_dump() if resp.usage else None
        return ChatResult(content=msg.content, tool_calls=calls, finish_reason=choice.finish_reason,
                          usage=usage, raw=msg.model_dump(exclude_none=True))
